"""Turn an operator's description of an MCP server into a signed connector bundle.

Arc is already an MCP client: a connector bundle with ``attachment = "mcp"`` is
what selects the SDK client. Until now the only way to add a server was to
hand-write that bundle. This module is the one place that does it for the
operator — and because an MCP server is third-party code reached over a wire or a
child process, the generated bundle IS the trust boundary. Every refusal that
protects it lives here, where the spec is built, before anything is written:

* **What may launch.** A stdio server must resolve to one executable on this host
  (an absolute path; a bare name is resolved once and pinned). No shell
  metacharacters, no relative paths, no shells or wrappers, no inline-code flags.
  Above personal tier the executable must also be on the operator's allowlist.
* **Where it may connect.** https only (plain http to loopback is a personal-tier
  convenience), no userinfo, no credential-looking query keys, and an SSRF guard:
  link-local, metadata, multicast and unspecified addresses are refused whether
  typed as a literal, as a numeric trick, or reached by name.
* **What it may expose.** The operator chooses tools after seeing what the server
  advertises. Each is registered as ``<name>__<verb>``, so a server can never
  take the name of a built-in tool, and its classification and capability tags
  come from the operator's choice, never from the server describing itself.
* **Who vouched.** Every generated byte is signed by the operator key and is
  re-verified at load, so editing the bundle afterwards makes it refuse to load.

Secrets are never part of the spec or the bundle. The spec names which fields the
server needs; the values go through the existing secret path at install time.
"""

